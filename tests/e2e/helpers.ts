import { expect, type Page } from "@playwright/test";
import { TEST_OWNER } from "../support/test-env";

export async function login(page: Page, email = TEST_OWNER.email, password = TEST_OWNER.password) {
  await page.goto("/admin/login");
  await page.getByLabel("Email").fill(email);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Sign in" }).click();
  await expect(page.getByRole("heading", { level: 1, name: /Hello/ })).toBeVisible({ timeout: 20_000 });
}

/** No sideways page scroll (code blocks/tables scroll inside their own containers). */
export async function expectNoHorizontalScroll(page: Page) {
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
  expect(overflow, "page should not scroll horizontally").toBeLessThanOrEqual(1);
}

